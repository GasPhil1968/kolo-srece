LINE_H = 10
BASE = 7
CELL_H = 9


def glyph_array(ch):
    rows = list(G[ch])
    w = max(len(r) for r in rows)
    rows += ['.' * w] * (CELL_H - len(rows))
    return np.array([[c == '#' for c in r.ljust(w, '.')] for r in rows], bool)


def build(name, outline):
    pad = 1 if outline else 0
    chars = sorted(G.keys(), key=ord)
    cols = 16
    cw = 8 + 2 * pad
    ch_ = CELL_H + 2 * pad
    rows = (len(chars) + cols - 1) // cols
    img = np.zeros((rows * ch_, cols * cw, 4), np.uint8)
    entries = []
    for i, c in enumerate(chars):
        a = glyph_array(c)
        h, w = a.shape
        x0 = (i % cols) * cw
        y0 = (i // cols) * ch_
        if outline:
            big = np.zeros((h + 2, w + 2), bool)
            big[1:-1, 1:-1] = a
            ol = np.zeros_like(big)
            for dy in (-1, 0, 1):
                for dx in (-1, 0, 1):
                    ol |= np.roll(np.roll(big, dy, 0), dx, 1)
            sub = img[y0:y0 + h + 2, x0:x0 + w + 2]
            sub[ol & ~big] = (0, 0, 0, 255)
            sub[big] = (255, 255, 255, 255)
            gw, gh = w + 2, h + 2
        else:
            sub = img[y0:y0 + h, x0:x0 + w]
            sub[a] = (255, 255, 255, 255)
            gw, gh = w, h
        adv = w + 1
        entries.append((ord(c), x0, y0, gw, gh, -pad, -pad, adv))
    folder = out_path('fonts')
    os.makedirs(folder, exist_ok=True)
    Image.fromarray(img, 'RGBA').save(os.path.join(folder, name + '.png'))
    lines = [
        '<?xml version="1.0"?>',
        '<font>',
        f'  <info face="{name}" size="{LINE_H}" bold="0" italic="0" charset="" unicode="1" stretchH="100" smooth="0" aa="0" padding="0,0,0,0" spacing="0,0"/>',
        f'  <common lineHeight="{LINE_H}" base="{BASE}" scaleW="{img.shape[1]}" scaleH="{img.shape[0]}" pages="1" packed="0"/>',
        '  <pages>',
        f'    <page id="0" file="{name}.png"/>',
        '  </pages>',
        f'  <chars count="{len(entries)}">',
    ]
    for (cid, x, y, w, h, xo, yo, adv) in entries:
        lines.append(f'    <char id="{cid}" x="{x}" y="{y}" width="{w}" height="{h}" xoffset="{xo}" yoffset="{yo}" xadvance="{adv}" page="0" chnl="15"/>')
    lines += ['  </chars>', '</font>']
    with open(os.path.join(folder, name + '.xml'), 'w') as f:
        f.write('\n'.join(lines))


def main():
    build('nl', False)
    build('nlo', True)


if __name__ == '__main__':
    main()
